"""Generate Terraform for aws_organizations_account (stdlib only, no Jinja2)."""

from __future__ import annotations

import re
from pathlib import Path


def _resource_name(account_name: str) -> str:
    name = re.sub(r"[^a-zA-Z0-9_]", "_", account_name)
    if name and name[0].isdigit():
        name = f"acct_{name}"
    return name or "member_account"


def _escape(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', '\\"')


class TerraformGenerator:
    def __init__(self, template_dir: str | Path | None = None) -> None:
        pass

    def render_account(
        self,
        *,
        account_name: str,
        account_email: str,
        parent_id: str,
        role_name: str = "OrganizationAccountAccessRole",
        account_tags: dict[str, str] | None = None,
    ) -> str:
        tags = account_tags or {}
        tag_lines = "\n".join(
            f'    {_escape(k)} = "{_escape(v)}"' for k, v in tags.items()
        )
        if tag_lines:
            tag_lines += "\n"
        tag_lines += '    ManagedBy = "account-factory"'

        return f'''# Account request generated by account-factory Lambda
# Account: {_escape(account_name)}

resource "aws_organizations_account" "{_resource_name(account_name)}" {{
  name      = "{_escape(account_name)}"
  email     = "{_escape(account_email)}"
  parent_id = "{_escape(parent_id)}"
  role_name = "{_escape(role_name)}"

  close_on_deletion = true

  tags = {{
{tag_lines}
  }}

  lifecycle {{
    ignore_changes = [role_name]
  }}
}}
'''

    @staticmethod
    def file_path_for_account(account_name: str) -> str:
        safe = re.sub(r"[^a-zA-Z0-9._-]", "-", account_name)
        # Kept under accounts/ for review. The apply buildspec copies these
        # into the repo root because Terraform does not load nested *.tf files.
        return f"accounts/{safe}.tf"
